#!/usr/bin/env node
// Pro licence codes for Avatar Studio (SuperEssence Studio).
// Codes are ECDSA P-256 / SHA-256 signatures verified offline by the app with the embedded public key.
//
//   node scripts/license.mjs keygen                 -> keys/license-private.jwk + src/core/licenseKey.ts (rebuild the app after)
//   node scripts/license.mjs sign --days 30 [--id client42]   -> prints a Pro code valid 30 days
//   node scripts/license.mjs sign --until 2027-12-31
//
// Keep keys/license-private.jwk secret and out of git: anyone holding it can mint Pro codes.
import { webcrypto as crypto } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PRIV = process.env.SE_LICENSE_KEY || path.join(ROOT, 'keys', 'license-private.jwk');
const PUB_TS = path.join(ROOT, 'web', 'src', 'core', 'licenseKey.ts');
const ALG = { name: 'ECDSA', namedCurve: 'P-256' };
const b64u = (buf) => Buffer.from(buf).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : undefined; };

const cmd = process.argv[2];
if (cmd === 'keygen') {
  if (fs.existsSync(PRIV) && !process.argv.includes('--force')) {
    console.error(`${PRIV} existe déjà (utilisez --force pour remplacer : les anciens codes deviendront invalides).`);
    process.exit(1);
  }
  const kp = await crypto.subtle.generateKey(ALG, true, ['sign', 'verify']);
  const priv = await crypto.subtle.exportKey('jwk', kp.privateKey);
  const pub = await crypto.subtle.exportKey('jwk', kp.publicKey);
  fs.mkdirSync(path.dirname(PRIV), { recursive: true });
  fs.writeFileSync(PRIV, JSON.stringify(priv), { mode: 0o600 });
  fs.writeFileSync(PUB_TS, `// Generated by scripts/license.mjs keygen. Public key only: safe to ship.\nexport const LICENSE_PUBLIC_JWK: JsonWebKey = ${JSON.stringify({ kty: pub.kty, crv: pub.crv, x: pub.x, y: pub.y })};\n`);
  console.log(`Clé privée : ${PRIV}\nClé publique : ${PUB_TS}`);
} else if (cmd === 'sign') {
  const jwk = JSON.parse(fs.readFileSync(PRIV, 'utf8'));
  const key = await crypto.subtle.importKey('jwk', jwk, ALG, false, ['sign']);
  let exp = arg('--until');
  if (!exp) {
    const d = new Date(Date.now() + Number(arg('--days') || 30) * 86400000);
    exp = d.toISOString().slice(0, 10);
  }
  const payload = { p: 'pro', e: exp, i: arg('--id') || Math.random().toString(36).slice(2, 10) };
  const body = b64u(Buffer.from(JSON.stringify(payload)));
  const sig = await crypto.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, key, Buffer.from(body));
  console.log(`SEPRO-${body}.${b64u(sig)}`);
  console.error(`(valide jusqu'au ${exp}, id ${payload.i})`);
} else {
  console.log('Usage: node scripts/license.mjs keygen | sign [--days N | --until YYYY-MM-DD] [--id ID]');
}
